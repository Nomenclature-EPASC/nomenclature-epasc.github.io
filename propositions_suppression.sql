-- À exécuter manuellement dans Supabase SQL Editor après relecture.
-- La colonne numero_id reprend exactement le type de numeros.id.
-- Elle n'a volontairement pas de clé étrangère : une demande acceptée
-- reste historisée après la suppression de la plante.

DO $$
DECLARE
    numero_id_type text;
BEGIN
    SELECT format_type(attribute.atttypid, attribute.atttypmod)
      INTO numero_id_type
      FROM pg_attribute AS attribute
     WHERE attribute.attrelid = 'public.numeros'::regclass
       AND attribute.attname = 'id'
       AND NOT attribute.attisdropped;

    IF numero_id_type IS NULL THEN
        RAISE EXCEPTION 'La colonne public.numeros.id est introuvable';
    END IF;

    EXECUTE format($create_table$
        CREATE TABLE IF NOT EXISTS public.propositions_suppression (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            numero_id %s NOT NULL,
            statut text NOT NULL DEFAULT 'en_attente'
                CHECK (statut IN ('en_attente', 'acceptee', 'refusee')),
            cree_le timestamptz NOT NULL DEFAULT now()
        )
    $create_table$, numero_id_type);
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS propositions_suppression_une_en_attente_par_plante
    ON public.propositions_suppression (numero_id)
    WHERE statut = 'en_attente';

ALTER TABLE public.propositions_suppression ENABLE ROW LEVEL SECURITY;

-- Les visiteurs anonymes ne peuvent jamais supprimer une plante.
REVOKE DELETE ON public.numeros FROM PUBLIC, anon;

REVOKE ALL ON public.propositions_suppression FROM PUBLIC, anon;
GRANT INSERT ON public.propositions_suppression TO anon;
GRANT SELECT ON public.propositions_suppression TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.propositions_suppression_id_seq TO anon, authenticated;

DROP POLICY IF EXISTS propositions_suppression_public_insert
    ON public.propositions_suppression;
CREATE POLICY propositions_suppression_public_insert
    ON public.propositions_suppression
    FOR INSERT TO anon
    WITH CHECK (
        statut = 'en_attente'
        AND EXISTS (
            SELECT 1
              FROM public.numeros
             WHERE numeros.id::text = propositions_suppression.numero_id::text
        )
    );

DROP POLICY IF EXISTS propositions_suppression_admin_select
    ON public.propositions_suppression;
CREATE POLICY propositions_suppression_admin_select
    ON public.propositions_suppression
    FOR SELECT TO authenticated
    USING (auth.role() = 'authenticated');

CREATE OR REPLACE VIEW public.propositions_suppression_visiteur
    WITH (security_barrier = true, security_invoker = false)
AS
    SELECT numero_id
      FROM public.propositions_suppression
     WHERE statut = 'en_attente';

REVOKE ALL ON public.propositions_suppression_visiteur FROM PUBLIC;
GRANT SELECT ON public.propositions_suppression_visiteur TO anon, authenticated;

DO $$
BEGIN
    EXECUTE format($create_function$
        CREATE OR REPLACE FUNCTION public.traiter_proposition_suppression(
            p_numero_id text,
            p_acceptee boolean
        )
        RETURNS void
        LANGUAGE plpgsql
        SECURITY DEFINER
        SET search_path = pg_catalog, public
        AS $function_body$
        BEGIN
            IF auth.role() <> 'authenticated' THEN
                RAISE EXCEPTION 'Accès réservé à l’administration';
            END IF;

            UPDATE public.propositions_suppression
               SET statut = CASE WHEN p_acceptee THEN 'acceptee' ELSE 'refusee' END
             WHERE numero_id::text = p_numero_id
               AND statut = 'en_attente';

            IF NOT FOUND THEN
                RAISE EXCEPTION 'Aucune demande en attente pour cette plante';
            END IF;

            IF p_acceptee THEN
                DELETE FROM public.numeros
                 WHERE id::text = p_numero_id;

                IF NOT FOUND THEN
                    RAISE EXCEPTION 'La plante associée est introuvable';
                END IF;
            END IF;
        END
        $function_body$
    $create_function$);
END
$$;

REVOKE ALL ON FUNCTION public.traiter_proposition_suppression(text, boolean)
    FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.traiter_proposition_suppression(text, boolean)
    TO authenticated;
